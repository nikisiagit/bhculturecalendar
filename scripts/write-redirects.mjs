/**
 * Writes public/_redirects for Cloudflare Pages.
 * Plain Node ESM so it runs without tsx IPC (sandbox-friendly).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const REDIRECTS_PATH = path.join(ROOT, "public", "_redirects");
const ARCHIVE_PATH = path.join(ROOT, "src", "data", "event-archive.json");

function slugify(value) {
  return (
    value
      .toLowerCase()
      .trim()
      .replace(/['']/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 80) || "item"
  );
}

function venuePath(name) {
  return `/venues/${slugify(name)}`;
}

function archiveRedirectTarget(entry) {
  if (entry.venue?.[0]) return venuePath(entry.venue[0]);
  if (entry.venueSlug) return `/venues/${entry.venueSlug}`;
  return "/whats-on";
}

async function fetchLiveEventKeys() {
  const api = (process.env.MOBILE_API_URL || "https://api.bhculturecalendar.co.uk").replace(
    /\/$/,
    ""
  );
  try {
    const res = await fetch(`${api}/events`, { headers: { Accept: "application/json" } });
    if (!res.ok) {
      console.warn(`write-redirects: API /events ${res.status} — homepage + seed redirects only`);
      return { keys: new Set(), ok: false };
    }
    const data = await res.json();
    const keys = new Set();
    for (const e of data.events ?? []) {
      if (e.id) {
        keys.add(String(e.id).toLowerCase());
        keys.add(String(e.id).replace(/-/g, "").toLowerCase());
      }
      if (e.slug?.trim()) keys.add(String(e.slug).trim().toLowerCase());
    }
    return { keys, ok: true };
  } catch (err) {
    console.warn("write-redirects: could not fetch live events:", err.message || err);
    return { keys: new Set(), ok: false };
  }
}

function uniqueArchiveEntries(archive) {
  const byId = new Map();
  for (const entry of Object.values(archive)) {
    if (entry?.id) byId.set(entry.id, entry);
  }
  return [...byId.values()];
}

function isLive(entry, liveKeys) {
  const id = entry.id.toLowerCase();
  const compact = id.replace(/-/g, "");
  const slug = (entry.slug || compact).toLowerCase();
  return liveKeys.has(id) || liveKeys.has(compact) || liveKeys.has(slug);
}

const archive = JSON.parse(fs.readFileSync(ARCHIVE_PATH, "utf8"));
const { keys: liveKeys, ok: apiOk } = await fetchLiveEventKeys();

const lines = [
  "# Generated by scripts/write-redirects.mjs — do not edit by hand.",
  "# Cloudflare Pages redirects (static export cannot use next.config redirects).",
  "",
  "# Homepage: permanent redirect (avoid App Router redirect() error shell)",
  "/    /whats-on    308",
  "",
];

let orphans = apiOk
  ? uniqueArchiveEntries(archive).filter((entry) => !isLive(entry, liveKeys))
  : uniqueArchiveEntries(archive).filter(
      (entry) => entry.id === "3e8f9c4288ed80579426d57f665c2fe5"
    );

if (orphans.length) {
  lines.push("# Removed events → venue (or /whats-on) so rankings are not soft-404s");
  for (const entry of orphans) {
    const target = archiveRedirectTarget(entry);
    const slug = entry.slug || entry.id.replace(/-/g, "");
    lines.push(`/event/${slug}    ${target}    301`);
    if (entry.id.includes("-") && entry.id !== slug) {
      lines.push(`/event/${entry.id}    ${target}    301`);
    }
  }
  lines.push("");
}

fs.writeFileSync(REDIRECTS_PATH, lines.join("\n") + "\n", "utf8");
console.log(
  `Wrote ${REDIRECTS_PATH} (${orphans.length} event redirect${orphans.length === 1 ? "" : "s"} + homepage 308)`
);
